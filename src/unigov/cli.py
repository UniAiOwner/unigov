@app.command()
def status(
    export: bool = typer.Option(False, "--export", help="Export dashboard to PROJECT_STATUS.md"),
    show_baseline: bool = typer.Option(False, "--show-baseline", help="Expand full M0-BASELINE subsystems"),
) -> None:
    """View Vision Lock, DAG Execution Tree, and optionally export PROJECT_STATUS.md."""
    conn = get_db()
    if export:
        _export_markdown_dashboard(conn)
        return

    vision = conn.execute("SELECT * FROM project_vision WHERE id = 1").fetchone()
    constraints = json.loads(vision["hard_constraints_json"])

    console.print(Panel(
        f"[bold cyan]{vision['project_name']}[/bold cyan]\n{vision['core_objective']}\n\n"
        f"[bold yellow]Locked Constraints:[/bold yellow]\n" + ("\n".join(f"• {c}" for c in constraints) or "None"),
        title="Vision & Governance Lock",
    ))

    tasks = conn.execute("SELECT * FROM tasks ORDER BY rowid ASC").fetchall()
    tree = Tree("[bold]Hierarchical Execution DAG[/bold]")
    nodes = {}

    baseline_files_count = 0
    baseline_subsystems_count = 0

    for t in tasks:
        # Collapse baseline child tasks unless --show-baseline is passed
        if not show_baseline and t["parent_id"] == "M0-BASELINE":
            baseline_subsystems_count += 1
            files = json.loads(t["target_files_json"] or "[]")
            baseline_files_count += len(files)
            continue

        color = {
            "COMPLETED": "green",
            "READY": "cyan",
            "IN_PROGRESS": "yellow",
            "FAILED": "red",
            "BLOCKED": "magenta",
        }.get(t["status"], "white")
        layer_badge = ""
        if "layer" in t.keys() and t["layer"]:
            layer_short = t["layer"].replace("LAYER_", "L").replace("_", " ")
            layer_badge = f" [dim cyan][{layer_short}][/dim cyan]"

        extra_info = ""
        if t["task_id"] == "M0-BASELINE" and not show_baseline:
            extra_info = " [dim](Verified Production Baseline: use --show-baseline to expand)[/dim]"

        label = f"[{color}][{t['status']}][/{color}]{layer_badge} [bold]{t['task_id']}[/bold] ({t['level']}): {t['title']}{extra_info}"
        parent_node = nodes.get(t["parent_id"], tree)
        nodes[t["task_id"]] = parent_node.add(label)

    console.print(tree)


@app.command()
def graph(
    mermaid: bool = typer.Option(True, "--mermaid", help="Render Mermaid.js dependency flowchart"),
    out: Optional[Path] = typer.Option(None, "--out", "-o", help="Save Mermaid diagram to a markdown file"),
) -> None:
    """Export visual task dependency graph in Mermaid.js format."""
    conn = get_db()
    tasks = conn.execute("SELECT task_id, level, title, status FROM tasks ORDER BY rowid ASC").fetchall()
    deps = conn.execute("SELECT task_id, depends_on_task_id FROM task_dependencies").fetchall()

    lines = ["```mermaid", "flowchart TD"]
    lines.append("    classDef completed fill:#14532d,stroke:#22c55e,color:#fff;")
    lines.append("    classDef ready fill:#164e63,stroke:#06b6d4,color:#fff;")
    lines.append("    classDef progress fill:#713f12,stroke:#eab308,color:#fff;")
    lines.append("    classDef failed fill:#7f1d1d,stroke:#ef4444,color:#fff;")
    lines.append("    classDef pending fill:#1e293b,stroke:#64748b,color:#e2e8f0;")

    status_class = {
        "COMPLETED": "completed",
        "READY": "ready",
        "IN_PROGRESS": "progress",
        "FAILED": "failed",
    }

    for t in tasks:
        safe_title = t["title"].replace('"', "'")
        node_id = t["task_id"].replace("-", "_")
        lines.append(f'    {node_id}["{t["task_id"]}: {safe_title}<br/>[{t["status"]}]"]:::{status_class.get(t["status"], "pending")}')

    for d in deps:
        src = d["depends_on_task_id"].replace("-", "_")
        dst = d["task_id"].replace("-", "_")
        lines.append(f"    {src} --> {dst}")

    lines.append("```")
    diagram = "\n".join(lines)

    if out:
        out.write_text(diagram + "\n", encoding="utf-8")
        console.print(f"[bold green]Saved Mermaid DAG graph to:[/bold green] {out.resolve()}")
    else:
        console.print(diagram)


