def _export_markdown_dashboard(conn, out_path: Path = Path("PROJECT_STATUS.md")) -> None:
    vision = conn.execute("SELECT * FROM project_vision WHERE id = 1").fetchone()
    constraints = json.loads(vision["hard_constraints_json"])
    tasks = conn.execute("SELECT * FROM tasks ORDER BY rowid ASC").fetchall()
    adrs = conn.execute("SELECT * FROM adr_ledger ORDER BY created_at ASC").fetchall()
    spend = conn.execute("SELECT COALESCE(SUM(estimated_cost_usd), 0) AS usd FROM api_usage_logs").fetchone()["usd"]

    total_leaf = sum(1 for t in tasks if t["level"] == "TASK")
    done_leaf = sum(1 for t in tasks if t["level"] == "TASK" and t["status"] == "COMPLETED")
    pct = round((done_leaf / total_leaf) * 100, 1) if total_leaf else 0.0

    lines = [
        f"# {vision['project_name']} — Project Status Dashboard",
        f"_Generated by Antigravity PM on {datetime.now().strftime('%Y-%m-%d %H:%M')}_",
        "",
        "## 1. Vision & Locked Constraints",
        f"**Core Objective:** {vision['core_objective']}",
        "",
        "### Non-Negotiable Constraints",
    ]
    lines.extend([f"- {c}" for c in constraints] or ["- _None locked yet_"])
    lines.extend([
        "",
        "## 2. Execution Progress",
        f"- **Atomic Tasks Completed:** {done_leaf} / {total_leaf} ({pct}%)",
        f"- **Cumulative AI Compute Cost:** ${spend:.4f} (~₹{spend * 84.5:.2f})",
        "",
        "| Task ID | Level | Title | Status | Target Files |",
        "| :--- | :--- | :--- | :--- | :--- |",
    ])
    for t in tasks:
        files = ", ".join(json.loads(t["target_files_json"] or "[]")) or "-"
        lines.append(f"| `{t['task_id']}` | {t['level']} | {t['title']} | **{t['status']}** | `{files}` |")

    lines.extend([
        "",
        "## 3. Architecture Decision Records (ADR Ledger)",
        "| ADR ID | Module | Decision | Rationale | Rejected |",
        "| :--- | :--- | :--- | :--- | :--- |",
    ])
    for a in adrs:
        lines.append(f"| `{a['adr_id']}` | {a['module_tag']} | {a['decision']} | {a['rationale']} | {a['rejected_alternatives'] or '-'} |")

    out_path.write_text("\n".join(lines) + "\n", encoding="utf-8")
    console.print(f"[bold green]Exported dashboard to:[/bold green] {out_path.resolve()}")


