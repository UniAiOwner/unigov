import typer
from rich.console import Console

console = Console()

GLOBAL_UNIGOV_DIR = Path.home() / ".unigov"
REGISTRY_FILE = GLOBAL_UNIGOV_DIR / "registry.json"


def get_registry_data() -> dict:
    if not REGISTRY_FILE.exists():
        return {"active_project": None, "active_path": None, "projects": {}}
    try:
        import json
        return json.loads(REGISTRY_FILE.read_text(encoding="utf-8"))
    except Exception:
        return {"active_project": None, "active_path": None, "projects": {}}


def save_registry_data(data: dict) -> None:
    try:
        import json
        GLOBAL_UNIGOV_DIR.mkdir(parents=True, exist_ok=True)
        REGISTRY_FILE.write_text(json.dumps(data, indent=2), encoding="utf-8")
    except Exception:
        pass


def record_active_project(project_name: str, project_root: Path) -> None:
    data = get_registry_data()
    abs_path = str(project_root.resolve())
    data["active_project"] = project_name
    data["active_path"] = abs_path
    if "projects" not in data:
        data["projects"] = {}
    data["projects"][project_name] = abs_path
    save_registry_data(data)


def _try_register_project(project_root: Path, gov_dir: Path) -> None:
    try:
        db_file = gov_dir / "state.db"
        if db_file.exists():
            c = sqlite3.connect(db_file)
            c.row_factory = sqlite3.Row
            row = c.execute("SELECT project_name FROM project_vision WHERE id = 1").fetchone()
            c.close()
            if row and row["project_name"]:
                record_active_project(row["project_name"], project_root)
    except Exception:
        pass


def resolve_gov_dir(project_root: Path = Path(".")) -> Path:
    """Resolves sovereign governance directory, respecting .unigov first then legacy .antigravity.
    If current directory is uninitialized, transparently falls back to the remembered active project."""
    abs_root = project_root.resolve()

    # User Home directory is NEVER a project workspace; transparently use active project
    if abs_root == Path.home():
        reg = get_registry_data()
        if reg.get("active_path"):
            active_p = Path(reg["active_path"])
            if (active_p / ".unigov" / "state.db").exists():
                return active_p / ".unigov"
            if (active_p / ".antigravity" / "state.db").exists():
                return active_p / ".antigravity"
            if (active_p / ".unigov").exists():
                return active_p / ".unigov"
            if (active_p / ".antigravity").exists():
                return active_p / ".antigravity"

    unigov_dir = project_root / ".unigov"
    ag_dir = project_root / ".antigravity"

    # 1. Direct match: initialized state.db in current directory
    if (unigov_dir / "state.db").exists():
        _try_register_project(project_root, unigov_dir)
        return unigov_dir
    if (ag_dir / "state.db").exists():
        _try_register_project(project_root, ag_dir)
        return ag_dir

    # 2. Support freshly created directory (e.g. during unigov init) if not home directory
    if unigov_dir.exists() and abs_root != Path.home() and (unigov_dir / "docs").exists():
        return unigov_dir

    # 3. Fallback to active project if run from generic directory (e.g. ~, /tmp, systemd service)
    reg = get_registry_data()
    if reg.get("active_path"):
        active_p = Path(reg["active_path"])
        if (active_p / ".unigov" / "state.db").exists():
            return active_p / ".unigov"
        if (active_p / ".antigravity" / "state.db").exists():
            return active_p / ".antigravity"
        if (active_p / ".unigov").exists():
            return active_p / ".unigov"
        if (active_p / ".antigravity").exists():
            return active_p / ".antigravity"

    if ag_dir.exists() and abs_root != Path.home():
        return ag_dir

    return unigov_dir


AG_DIR = Path(".unigov")
DB_PATH = AG_DIR / "state.db"


def init_workspace_folders(project_root: Path = Path(".")) -> Path:
    """Initializes the sovereign .unigov directory tree with dual git-tracked and git-ignored zones."""
    gov_dir = project_root / ".unigov"
    gov_dir.mkdir(parents=True, exist_ok=True)

    # Git-Tracked directories
    (gov_dir / "docs").mkdir(exist_ok=True)
    (gov_dir / "adrs").mkdir(exist_ok=True)
    (gov_dir / "contracts").mkdir(exist_ok=True)
    (gov_dir / "reports").mkdir(exist_ok=True)

    # Git-Ignored runtime directories
    (gov_dir / "backups").mkdir(exist_ok=True)
    (gov_dir / "cache").mkdir(exist_ok=True)

    # Auto-generate .unigov/.gitignore
    gitignore_path = gov_dir / ".gitignore"
    if not gitignore_path.exists():
        gitignore_content = """# Sovereign Governance Runtime & Cache (Auto-generated by UniGov)
state.db
state.db-wal
state.db-shm
backups/
cache/
*.tmp
"""
        gitignore_path.write_text(gitignore_content, encoding="utf-8")

    return gov_dir


def migrate_legacy_store(project_root: Path = Path(".")) -> Tuple[bool, str]:
    """Migrates legacy .antigravity/ directory to modern .unigov/ workspace."""
    legacy_dir = project_root / ".antigravity"
    target_dir = project_root / ".unigov"

    if not legacy_dir.exists():
        return False, "No legacy .antigravity directory found."

    init_workspace_folders(project_root)

    migrated_items = []
    for item in legacy_dir.glob("*"):
        dest = target_dir / item.name
        if item.is_file():
            shutil.copy2(item, dest)
            migrated_items.append(item.name)
        elif item.is_dir():
            if dest.exists():
                for sub in item.glob("*"):
                    shutil.copy2(sub, dest / sub.name)
            else:
                shutil.copytree(item, dest)
            migrated_items.append(f"{item.name}/")

    return True, f"Migrated {len(migrated_items)} items from .antigravity to .unigov: {', '.join(migrated_items)}"


def get_db(require_init: bool = True) -> sqlite3.Connection:
    global AG_DIR, DB_PATH
    active_dir = resolve_gov_dir()
    db_file = active_dir / "state.db"

    # Support isolated testing fixture monkeypatching
    if AG_DIR != Path(".unigov") and AG_DIR != Path(".antigravity"):
        active_dir = AG_DIR
        db_file = DB_PATH

    if require_init and not db_file.exists():
        console.print("[bold red]Error:[/bold red] Workspace not initialized. Run [cyan]unigov init[/cyan] first.")
        raise typer.Exit(1)

    active_dir.mkdir(parents=True, exist_ok=True)
    conn = sqlite3.connect(db_file)
    conn.row_factory = sqlite3.Row
    conn.execute("PRAGMA foreign_keys = ON;")
    conn.execute("PRAGMA journal_mode = WAL;")
    conn.execute("PRAGMA busy_timeout = 5000;")
    init_schema(conn)
    return conn


def init_schema(conn: sqlite3.Connection) -> None:
    conn.executescript("""
    CREATE TABLE IF NOT EXISTS project_vision (
        id INTEGER PRIMARY KEY CHECK (id = 1),
        project_name TEXT NOT NULL,
        core_objective TEXT NOT NULL,
        hard_constraints_json TEXT NOT NULL,
        updated_at DATETIME DEFAULT CURRENT_TIMESTAMP
    );

    CREATE TABLE IF NOT EXISTS ingested_docs (
        doc_id INTEGER PRIMARY KEY AUTOINCREMENT,
        file_path TEXT UNIQUE NOT NULL,
        file_hash TEXT NOT NULL,
        last_ingested_at DATETIME DEFAULT CURRENT_TIMESTAMP
    );

    CREATE TABLE IF NOT EXISTS tasks (
        task_id TEXT PRIMARY KEY,
        parent_id TEXT REFERENCES tasks(task_id) ON DELETE CASCADE,
        level TEXT NOT NULL CHECK(level IN ('MILESTONE', 'MODULE', 'TASK')),
        title TEXT NOT NULL,
        description TEXT NOT NULL,
        target_files_json TEXT,
        verify_cmd TEXT,
        status TEXT NOT NULL DEFAULT 'PENDING'
            CHECK(status IN ('PENDING', 'READY', 'IN_PROGRESS', 'VERIFYING', 'COMPLETED', 'FAILED', 'BLOCKED')),
        created_at DATETIME DEFAULT CURRENT_TIMESTAMP,
        completed_at DATETIME
    );

    CREATE TABLE IF NOT EXISTS task_dependencies (
        task_id TEXT NOT NULL REFERENCES tasks(task_id) ON DELETE CASCADE,
        depends_on_task_id TEXT NOT NULL REFERENCES tasks(task_id) ON DELETE CASCADE,
        PRIMARY KEY (task_id, depends_on_task_id),
        CHECK (task_id != depends_on_task_id)
    );

    CREATE TABLE IF NOT EXISTS adr_ledger (
        adr_id TEXT PRIMARY KEY,
        module_tag TEXT NOT NULL,
        decision TEXT NOT NULL,
        rationale TEXT NOT NULL,
        rejected_alternatives TEXT,
        status TEXT DEFAULT 'FINALIZED' CHECK(status IN ('FINALIZED', 'PROPOSED', 'DEPRECATED')),
        created_at DATETIME DEFAULT CURRENT_TIMESTAMP
    );

    CREATE TABLE IF NOT EXISTS audit_logs (
        log_id INTEGER PRIMARY KEY AUTOINCREMENT,
        task_id TEXT REFERENCES tasks(task_id),
        check_type TEXT NOT NULL,
        passed INTEGER NOT NULL CHECK(passed IN (0, 1)),
        output_snippet TEXT,
        checked_at DATETIME DEFAULT CURRENT_TIMESTAMP
    );

    CREATE TABLE IF NOT EXISTS git_checkpoints (
        checkpoint_id INTEGER PRIMARY KEY AUTOINCREMENT,
        task_id TEXT NOT NULL REFERENCES tasks(task_id),
        tag_name TEXT UNIQUE NOT NULL,
        commit_hash TEXT NOT NULL,
        had_uncommitted_changes INTEGER NOT NULL DEFAULT 0,
        created_at DATETIME DEFAULT CURRENT_TIMESTAMP
    );

    CREATE TABLE IF NOT EXISTS api_usage_logs (
        usage_id INTEGER PRIMARY KEY AUTOINCREMENT,
        command_name TEXT NOT NULL,
        model_name TEXT NOT NULL,
        prompt_tokens INTEGER NOT NULL,
        output_tokens INTEGER NOT NULL,
        estimated_cost_usd REAL NOT NULL,
        created_at DATETIME DEFAULT CURRENT_TIMESTAMP
    );

    CREATE TABLE IF NOT EXISTS invariants (
        invariant_id TEXT PRIMARY KEY,
        layer TEXT NOT NULL,
        title TEXT NOT NULL,
        rule_type TEXT NOT NULL,
        file_patterns_json TEXT NOT NULL,
        params_json TEXT NOT NULL,
        enforcement TEXT NOT NULL CHECK(enforcement IN ('BLOCK_BUILD', 'WARN')),
        source_doc TEXT NOT NULL,
        created_at DATETIME DEFAULT CURRENT_TIMESTAMP
    );
    """)

    # Ensure tasks table has modern metadata columns
    cols = [r[1] for r in conn.execute("PRAGMA table_info(tasks)").fetchall()]
    if "layer" not in cols:
        conn.execute("ALTER TABLE tasks ADD COLUMN layer TEXT DEFAULT 'LAYER_1_DOMAIN'")
    if "is_baseline" not in cols:
        conn.execute("ALTER TABLE tasks ADD COLUMN is_baseline INTEGER DEFAULT 0")
    if "subsystem" not in cols:
        conn.execute("ALTER TABLE tasks ADD COLUMN subsystem TEXT")

    conn.commit()
